// Rules for contact messages and replies, shared by the Studio and the Netlify Functions, so both sides
// check the same things. The reply text is Portable Text with only paragraphs, lists, bold, italic,
// underline and links. Plain JavaScript, so the functions can import it without a TypeScript step.

export const MESSAGE_TYPE = 'contactMessage'
/** The dot keeps messages out of the public API of the (public) dataset. */
export const MESSAGE_ID_PREFIX = 'message.'
export const ASSET_SOURCE = 'getdeveloper-message-reply'

export const MAX_REPLY_SUBJECT_LENGTH = 150
export const MAX_REPLY_TEXT_LENGTH = 10_000
const MAX_REPLY_BLOCKS = 300
const MAX_LIST_LEVEL = 3

export const MAX_REPLY_FILES = 5
export const MAX_REPLY_FILES_BYTES = 10 * 1024 * 1024
export const REPLY_FILE_TYPES = ['application/pdf', 'image/jpeg', 'image/png']
export const MAX_REPLY_PHOTOS = 6
/** Per upload; the mail gets a smaller copy. */
export const MAX_REPLY_PHOTO_BYTES = 20 * 1024 * 1024
export const REPLY_PHOTO_TYPES = ['image/jpeg', 'image/png']

export const MAX_REACTION_LENGTH = 3000

export const REPLY_DECORATORS = ['strong', 'em', 'underline']
export const REPLY_LISTS = ['bullet', 'number']

export const MAIL_STATUSES = [
  {title: 'Wordt verstuurd', value: 'pending'},
  {title: 'Verzonden', value: 'sent'},
  {title: 'Mislukt', value: 'failed'},
  {title: 'Onzeker (mogelijk verzonden)', value: 'uncertain'},
  {title: 'Niet geconfigureerd', value: 'notConfigured'},
]

const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/
const REPLY_KEY_PATTERN = /^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/
const SANITY_KEY_PATTERN = /^[A-Za-z0-9_-]{1,64}$/
const FILE_ASSET_ID = /^file-[0-9a-f]{40}-[a-z0-9]{1,8}$/
const IMAGE_ASSET_ID = /^image-[0-9a-f]{40}-\d{1,5}x\d{1,5}-[a-z]{3,4}$/

export function isUuid(value) {
  return typeof value === 'string' && UUID.test(value)
}

export function messageId(uuid) {
  return `${MESSAGE_ID_PREFIX}${uuid}`
}

/** "message.<uuid>" only. */
export function isMessageId(value) {
  return (
    typeof value === 'string' &&
    value.startsWith(MESSAGE_ID_PREFIX) &&
    isUuid(value.slice(MESSAGE_ID_PREFIX.length))
  )
}

/** Generated by the Studio per message; the same key never sends twice. */
export function isReplyKey(value) {
  return typeof value === 'string' && REPLY_KEY_PATTERN.test(value)
}

export function isFileAssetId(value) {
  return typeof value === 'string' && FILE_ASSET_ID.test(value)
}

export function isImageAssetId(value) {
  return typeof value === 'string' && IMAGE_ASSET_ID.test(value)
}

/** One line, without control characters. */
export function normalizeReplySubject(value) {
  if (typeof value !== 'string') return null
  const subject = value.replace(/[\u0000-\u001f\u007f]+/g, ' ').trim()
  return subject && subject.length <= MAX_REPLY_SUBJECT_LENGTH ? subject : null
}

/** Absolute http(s), mailto and tel links only: a site path means nothing in a mail. */
export function replyLinkHref(value) {
  if (typeof value !== 'string') return null
  const href = value.trim()
  if (!href || /[\u0000-\u001f\u007f\s]/.test(href)) return null
  return /^(https?:\/\/[^\s/]+|mailto:[^\s]+|tel:[+0-9][0-9 ()+-]*)/i.test(href) ? href : null
}

function isRecord(value) {
  return typeof value === 'object' && value !== null && !Array.isArray(value)
}

function isKey(value) {
  return typeof value === 'string' && SANITY_KEY_PATTERN.test(value)
}

/** Text without control characters other than line breaks. */
function cleanText(value) {
  return value.replace(/\r\n?/g, '\n').replace(/[\u0000-\u0008\u000b-\u001f\u007f]/g, '')
}

export function blockText(block) {
  return block.children.map((child) => child.text).join('')
}

/**
 * The editor's value rebuilt from allowed parts only: unknown marks, styles and objects are dropped,
 * an invalid link loses its link. Null when empty, too long or not Portable Text.
 */
export function normalizeReplyBody(value) {
  if (!Array.isArray(value) || value.length > MAX_REPLY_BLOCKS) return null

  const blocks = []
  let length = 0

  for (const block of value) {
    if (!isRecord(block) || block._type !== 'block') continue
    if (!isKey(block._key) || !Array.isArray(block.children)) return null

    const markDefs = (Array.isArray(block.markDefs) ? block.markDefs : []).flatMap((mark) => {
      const href = isRecord(mark) ? replyLinkHref(mark.href) : null
      return isRecord(mark) && mark._type === 'replyLink' && isKey(mark._key) && href
        ? [{_type: 'replyLink', _key: mark._key, href}]
        : []
    })
    const allowedMarks = new Set([...REPLY_DECORATORS, ...markDefs.map((mark) => mark._key)])
    const children = []

    for (const child of block.children) {
      if (!isRecord(child) || child._type !== 'span') continue
      if (!isKey(child._key) || typeof child.text !== 'string') return null

      const text = cleanText(child.text)
      length += text.length
      children.push({
        _type: 'span',
        _key: child._key,
        text,
        marks: (Array.isArray(child.marks) ? child.marks : []).filter(
          (mark) => typeof mark === 'string' && allowedMarks.has(mark),
        ),
      })
    }

    const used = new Set(children.flatMap((child) => child.marks))
    const listItem = REPLY_LISTS.find((list) => list === block.listItem)
    const level =
      typeof block.level === 'number' && Number.isInteger(block.level)
        ? Math.min(Math.max(block.level, 1), MAX_LIST_LEVEL)
        : 1

    blocks.push({
      _type: 'block',
      _key: block._key,
      style: 'normal',
      ...(listItem ? {listItem, level} : {}),
      markDefs: markDefs.filter((mark) => used.has(mark._key)),
      children:
        children.length > 0
          ? children
          : [{_type: 'span', _key: `${block._key}-0`, text: '', marks: []}],
    })
  }

  // Empty lines at the end are left out.
  while (blocks.length > 0 && !blockText(blocks[blocks.length - 1]).trim()) blocks.pop()

  return blocks.some((block) => blockText(block).trim()) && length <= MAX_REPLY_TEXT_LENGTH
    ? blocks
    : null
}

/** Plain text for the text part of the mail and the Studio history. */
export function replyBodyToText(blocks) {
  const lines = []
  const counters = []
  let previousList = false

  for (const block of blocks) {
    const links = new Map(block.markDefs.map((mark) => [mark._key, mark.href]))
    const text = block.children
      .map((child) => {
        const href = child.marks.map((mark) => links.get(mark)).find(Boolean)
        return href && href !== child.text && `mailto:${child.text}` !== href
          ? `${child.text} (${href})`
          : child.text
      })
      .join('')

    if (block.listItem) {
      const level = block.level ?? 1
      counters.length = level
      counters[level - 1] = (counters[level - 1] ?? 0) + 1
      const marker = block.listItem === 'number' ? `${counters[level - 1]}.` : '•'
      lines.push(`${previousList ? '' : '\n'}${'  '.repeat(level - 1)}${marker} ${text}`)
      previousList = true
    } else {
      counters.length = 0
      lines.push(`\n${text}`)
      previousList = false
    }
  }

  return lines
    .join('\n')
    .replace(/\n{3,}/g, '\n\n')
    .trim()
}

/** Line breaks kept, other control characters removed; null when empty or too long. */
export function normalizeReaction(value) {
  if (typeof value !== 'string') return null
  const message = cleanText(value).trim()
  return message && message.length <= MAX_REACTION_LENGTH ? message : null
}
